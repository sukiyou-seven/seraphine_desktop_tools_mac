import AppKit
import SwiftUI

/// 剪贴板历史：轮询系统剪贴板 → 内存 + Redis + 本地文件。
///
/// **只记文本**。图片、文件、富文本等非文本内容一律跳过，
/// 所以本地固化文件里永远不会出现图片数据（也解释了为什么文件能压在 2 MB 以内）。
/// Redis 负责「读得快」，本地文件负责「关机重启后还在」。
@MainActor
final class ClipboardService: ObservableObject {

    /// 历史条目（最新在前）。界面直接读它。
    @Published private(set) var entries: [ClipboardEntry] = []
    /// Redis 同步情况的一句话说明（给界面显示）。
    @Published private(set) var redisNote = "尚未载入"
    /// 固化文件当前大小。
    @Published private(set) var fileBytes = 0
    /// 是否在记录（关掉只是不再记新的，已有历史照常保留）。
    @Published private(set) var recording = true

    /// 由 AppModel 注入：取当前的 Redis 连接参数（返回 nil 表示没配 Redis）。
    /// 约定在主线程调用。
    var redisTarget: () -> ClipboardRedisTarget? = { nil }

    let filePath: String

    /// 轮询间隔：0.7 秒足够跟手，又不会一直在那儿空转。
    private static let pollInterval: TimeInterval = 0.7
    /// 落盘与 Redis 同步都走这条串行队列，别让「复制」这个动作卡住界面。
    private let queue = DispatchQueue(label: "dbmanager.clipboard", qos: .utility)
    private var timer: Timer?
    /// 上一次看到的剪贴板变更计数，用来判断「是不是有新内容」。
    private var changeCount = 0

    init(filePath: String = Paths.clipboardFile.path) {
        self.filePath = filePath
    }

    static var maxFileBytes: Int { ClipboardHistory.maxFileBytes }
    static var maxEntries: Int { ClipboardHistory.maxEntries }

    // MARK: 生命周期

    /// 开始监听并载入已有历史。App 启动时调一次。
    func start(recording: Bool) {
        self.recording = recording
        changeCount = NSPasteboard.general.changeCount
        // 先用本地文件把列表填上（读文件很快），再后台去拉 Redis，别把启动路径堵住。
        entries = ClipboardHistory.readFile(filePath)
        fileBytes = ClipboardHistory.fileSize(filePath)
        syncFromRedis()
        if timer == nil {
            let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
                // 定时器挂在主 RunLoop 上，回调必定在主线程；编译器不知道，这里显式声明。
                MainActor.assumeIsolated { self?.poll() }
            }
            RunLoop.main.add(timer, forMode: .common)   // .common：列表滚动时也别停
            self.timer = timer
        }
        Diag.log("剪贴板历史：开始监听（记录 \(recording ? "开" : "关")，本地已有 \(entries.count) 条）")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// 切换记录开关。关掉期间的剪贴板变化不会在重新打开时被翻出来记一遍。
    func setRecording(_ on: Bool) {
        guard recording != on else { return }
        recording = on
        changeCount = NSPasteboard.general.changeCount
        Diag.log("剪贴板历史：记录开关 → \(on ? "开" : "关")")
    }

    // MARK: 轮询

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard recording else { return }
        guard !Self.isConcealed(pasteboard) else {
            Diag.log("剪贴板历史：跳过被标记为密码/瞬态的内容")
            return
        }
        // 只要文本：图片、文件、其它富内容在这里就被挡掉了。
        guard let text = pasteboard.string(forType: .string) else { return }
        record(text)
    }

    /// 系统约定：密码管理器等会把内容打上这些类型，表示「别记进历史」。
    static func isConcealed(_ pasteboard: NSPasteboard) -> Bool {
        let concealed: Set<String> = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
        ]
        let types = Set((pasteboard.types ?? []).map { $0.rawValue })
        return !types.isDisjoint(with: concealed)
    }

    private func record(_ text: String) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        entries = ClipboardHistory.add(trimmed, to: entries)
        persist()
    }

    // MARK: 载入 / 持久化

    /// 从 Redis 拉一次（快、通常也更新），与本地文件合并成最新列表，再写回文件。
    func syncFromRedis() {
        guard let target = redisTarget() else {
            redisNote = "未配置 Redis：只用本地文件"
            return
        }
        redisNote = "正在读 Redis…"
        let path = filePath
        // 读 Redis、合并、写回都在后台队列上跑：这条路径别把界面卡住。
        queue.async { [weak self] in
            let loaded = ClipboardHistory.load(filePath: path, redis: target)
            let fileError = ClipboardHistory.writeFile(path, entries: loaded.entries)
            let size = ClipboardHistory.fileSize(path)
            let note = fileError.map { "已读 Redis，但写本地文件失败：\($0)" } ?? loaded.note
            DispatchQueue.main.async {
                guard let self else { return }
                self.entries = loaded.entries
                self.fileBytes = size
                self.redisNote = note
            }
        }
    }

    /// 落盘 + 同步 Redis（都在后台做）。
    private func persist() {
        let snapshot = entries
        let path = filePath
        let target = redisTarget()
        queue.async { [weak self] in
            let fileError = ClipboardHistory.writeFile(path, entries: snapshot)
            let note = fileError.map { "本地文件写入失败：\($0)" }
                ?? target.map { ClipboardHistory.writeRedis($0, entries: snapshot) }
                ?? "未配置 Redis：只写了本地文件"
            let size = ClipboardHistory.fileSize(path)
            DispatchQueue.main.async {
                guard let self else { return }
                self.fileBytes = size
                self.redisNote = note
                if let fileError { Diag.log("剪贴板历史：写文件失败 — \(fileError)") }
            }
        }
    }

    // MARK: 操作

    /// 把某条历史写回系统剪贴板（点列表里任意一条走的就是这里）。
    func copy(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        // 这次写入是我们自己干的，同步一下计数，免得轮询又把它当成"新内容"记一遍。
        changeCount = pasteboard.changeCount
        Diag.log("剪贴板历史：复制回剪贴板（\(entry.bytes) 字节）")
    }

    func remove(_ entry: ClipboardEntry) {
        entries = ClipboardHistory.remove(id: entry.id, from: entries)
        persist()
    }

    func clear() {
        guard !entries.isEmpty else { return }
        entries = []
        persist()
    }
}
